using System.Text;
using System.Text.RegularExpressions;

namespace Cmdr.Core.Processes;

/// <summary>
/// Escaping for running a batch file through <c>cmd.exe /d /v:off /s /c</c>, ported from the cross-spawn npm package (MIT),
/// whose rules are based on https://qntm.org/cmd.
/// </summary>
internal static class WindowsCmdEscaping
{
    /// <summary>cmd.exe metacharacters, each of which is caret-escaped.</summary>
    private static readonly Regex MetaChars = new(@"([()\][%!^""`<>&|;, *?])", RegexOptions.CultureInvariant);

    /// <summary>A run of backslashes followed by a double quote.</summary>
    private static readonly Regex BackslashesBeforeQuote = new(@"(\\*)""", RegexOptions.CultureInvariant);

    /// <summary>A run of backslashes at the end of the string.</summary>
    private static readonly Regex BackslashesAtEnd = new(@"(\\*)\z", RegexOptions.CultureInvariant);

    /// <summary>
    /// A cmd-shim generated by npm/pnpm in <c>node_modules\.bin</c>. Such shims re-expand their arguments through
    /// <c>%*</c>, so cmd parses them twice and the metacharacters need a second round of escaping.
    /// </summary>
    private static readonly Regex CmdShim = new(@"node_modules[\\/]\.bin[\\/][^\\/]+\.cmd\z", RegexOptions.CultureInvariant | RegexOptions.IgnoreCase);

    /// <summary>Caret-escapes the metacharacters of a command (the executable path).</summary>
    public static string EscapeCommand(string command)
    {
        ArgumentNullException.ThrowIfNull(command);
        return MetaChars.Replace(command, @"^$1");
    }

    /// <summary>Quotes one argument for the MSVC command-line parser and caret-escapes it for cmd.exe.</summary>
    public static string EscapeArgument(string argument, bool doubleEscapeMetaChars = false)
    {
        ArgumentNullException.ThrowIfNull(argument);

        // Backslashes before a quote are doubled and the quote escaped.
        string arg = BackslashesBeforeQuote.Replace(argument, @"$1$1\""");

        // Trailing backslashes are doubled so they do not escape the closing quote added next.
        arg = BackslashesAtEnd.Replace(arg, @"$1$1");

        arg = "\"" + arg + "\"";

        // This also escapes the two wrapping quotes.
        arg = MetaChars.Replace(arg, @"^$1");
        return doubleEscapeMetaChars ? MetaChars.Replace(arg, @"^$1") : arg;
    }

    /// <summary>
    /// Builds the argument string for <c>cmd.exe</c>: <c>/d /v:off /s /c "&lt;escaped path&gt; &lt;escaped args&gt;"</c>.
    /// <c>/v:off</c> keeps delayed expansion off whatever the registry enables, so <c>!var!</c> in an argument is not expanded.
    /// Pass it as <c>ProcessStartInfo.Arguments</c> (raw), not through <c>ArgumentList</c>, which would quote it again.
    /// </summary>
    public static string BuildCmdArguments(string resolvedPath, IReadOnlyList<string> args) =>
        "/d /v:off /s /c \"" + BuildCommand(resolvedPath, args) + "\"";

    /// <summary>
    /// The command cmd.exe runs: the escaped path and arguments, as cmd parses them once <c>/s</c> has removed the quotes
    /// around them (or once a variable holding them has been expanded).
    /// </summary>
    public static string BuildCommand(string resolvedPath, IReadOnlyList<string> args)
    {
        ArgumentNullException.ThrowIfNull(resolvedPath);
        ArgumentNullException.ThrowIfNull(args);

        bool doubleEscape = CmdShim.IsMatch(resolvedPath);
        var sb = new StringBuilder(EscapeCommand(resolvedPath));
        foreach (string arg in args)
        {
            sb.Append(' ').Append(EscapeArgument(arg, doubleEscape));
        }

        return sb.ToString();
    }
}
